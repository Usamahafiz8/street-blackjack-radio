#!/usr/bin/env node
// Builds the static test player for hosting on Vercel (or any static host).
// AzuraCast and the registry API can NOT run on Vercel; the player points at them via API_BASE.
//
//   API_BASE=https://<radio-server> node infra/vercel/build-player.mjs
//   npx vercel deploy .vercel-build/player --prod
//
// The radio-server address can also be changed later without redeploying:
//   https://<your-app>.vercel.app/?api=https://<new-radio-server>   (remembered on that device)
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const src = `${root}player`;
const out = `${root}.vercel-build/player`;
const apiBase = (process.env.API_BASE || '').replace(/\/+$/, '');
if (apiBase && !apiBase.startsWith('https://')) {
  console.error('API_BASE must be https:// (an HTTPS page cannot load an http:// API or stream).');
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(src, out, { recursive: true, filter: (p) => !/[\\/]tools([\\/]|$)/.test(p) });

writeFileSync(
  `${out}/config.js`,
  `// Generated by infra/vercel/build-player.mjs\nwindow.SBR_CONFIG = { apiBase: ${JSON.stringify(apiBase)}, preferHls: false, refreshMs: 15000 };\n`,
);

writeFileSync(
  `${out}/vercel.json`,
  JSON.stringify(
    {
      cleanUrls: false,
      headers: [
        { source: '/(sw.js|config.js|index.html)', headers: [{ key: 'Cache-Control', value: 'no-cache' }] },
        { source: '/(.*)', headers: [{ key: 'X-Content-Type-Options', value: 'nosniff' }, { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' }] },
      ],
    },
    null,
    2,
  ),
);

console.log(`Built ${out}`);
console.log(`API_BASE: ${apiBase || '(none - set it with ?api=... or the Diagnostics "Radio server" field)'}`);
