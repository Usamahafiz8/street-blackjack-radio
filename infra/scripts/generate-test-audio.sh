#!/usr/bin/env bash
# Generates 100% synthetic, licence-free test "DJ mixes" for the proof of concept.
# No third-party music or samples: drum pattern and tones come from ffmpeg's signal
# generator, and the voice comes from the open-source espeak-ng speech synthesiser.
#
# Every minute of every mix starts with a spoken marker ("UK Rap, test mix 2, minute 7"),
# so you can HEAR the broadcast position when testing "leave and come back".
#
# Usage (on the server):  bash generate-test-audio.sh [output_dir]
# Env: MIXES=4 MIX_MINUTES=12
set -euo pipefail
OUT="${1:-/opt/sbradio/test-audio}"
MIXES="${MIXES:-4}"
MIX_MINUTES="${MIX_MINUTES:-12}"
command -v ffmpeg >/dev/null && command -v espeak-ng >/dev/null || { echo "Needs ffmpeg and espeak-ng" >&2; exit 1; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# station_shortcode | spoken name | genre tag | bpm | base pitch Hz
STATIONS=(
  "uk_rap|UK Rap|UK Rap|140|110"
  "afrobeats|Afrobeats|Afrobeats|108|146.8"
  "dancehall|Dancehall|Dancehall|96|98"
  "rnb|R and B|R&B|72|130.8"
  "oldschool|Old School|Hip-Hop|92|116.5"
)
# Stations listed here get their mixes as ONE long file in $OUT/originals/ instead (to demo split-mix).
LONG_MIX_STATIONS="${LONG_MIX_STATIONS:-oldschool}"

speak() { # speak "text" out.wav
  espeak-ng -v en-gb -s 145 -w "$2" "$1" 2>/dev/null || espeak-ng -s 145 -w "$2" "$1"
}

segment() { # segment bpm pitchHz seconds voice.wav out.wav
  local bpm=$1 hz=$2 secs=$3 voice=$4 out=$5
  local beat; beat=$(awk "BEGIN{print 60/$bpm}")
  # kick on every beat, off-beat hi-hat (noise), and a slow-pulsing tone whose pitch marks the minute
  local expr="0.7*sin(2*PI*52*t)*exp(-12*mod(t\,${beat}))+0.05*(2*random(0)-1)*exp(-40*mod(t+${beat}/2\,${beat}))+0.12*sin(2*PI*${hz}*t)*(0.6+0.4*sin(2*PI*t/(4*${beat})))"
  ffmpeg -nostdin -loglevel error -y \
    -f lavfi -i "aevalsrc=${expr}:s=44100:d=${secs}" \
    -i "$voice" \
    -filter_complex "[1:a]aresample=44100,adelay=300|300,volume=2.2[v];[0:a][v]amix=inputs=2:duration=first:normalize=0,alimiter=limit=0.9" \
    -ac 2 -c:a pcm_s16le "$out"
}

make_mix() { # make_mix code name genre bpm basehz m target
  local code=$1 name=$2 genre=$3 bpm=$4 basehz=$5 m=$6 target=$7
  : > "$TMP/list.txt"
  for minute in $(seq 0 $((MIX_MINUTES - 1))); do
    speak "${name}. Test mix ${m}. Minute ${minute}." "$TMP/v.wav"
    # pitch steps up a semitone each minute so position is audible even without the voice
    hz=$(awk "BEGIN{printf \"%.2f\", $basehz * 2^(($minute + 3*($m-1))/12)}")
    segment "$bpm" "$hz" 60 "$TMP/v.wav" "$TMP/seg-${minute}.wav"
    echo "file '$TMP/seg-${minute}.wav'" >> "$TMP/list.txt"
  done
  ffmpeg -nostdin -loglevel error -y -f concat -safe 0 -i "$TMP/list.txt" -c:a pcm_s16le "$target"
}

tag_mp3() { # tag_mp3 in.wav out.mp3 title artist genre
  ffmpeg -nostdin -loglevel error -y -i "$1" -c:a libmp3lame -b:a 320k \
    -metadata title="$3" -metadata artist="$4" \
    -metadata album="Street Blackjack Radio - generated test audio" -metadata genre="$5" \
    -metadata comment="Synthetic test audio generated by generate-test-audio.sh. No third-party content." "$2"
}

for entry in "${STATIONS[@]}"; do
  IFS='|' read -r code name genre bpm basehz <<<"$entry"
  if [[ " $LONG_MIX_STATIONS " == *" $code "* ]]; then
    # One long DJ mix (MIXES x MIX_MINUTES) with a short quiet transition between sections,
    # stored as an "original" to be split into ~30 min parts by tools/split-mix.
    mkdir -p "$OUT/originals"
    target="$OUT/originals/${code}-long-mix-1.mp3"
    if [[ -s "$target" ]]; then echo "exists: $target"; continue; fi
    echo "generating $target (long mix)"
    : > "$TMP/long.txt"
    ffmpeg -nostdin -loglevel error -y -f lavfi -i anullsrc=r=44100:cl=stereo -t 1.2 -c:a pcm_s16le "$TMP/gap.wav"
    for m in $(seq 1 "$MIXES"); do
      make_mix "$code" "$name" "$genre" "$bpm" "$basehz" "$m" "$TMP/long-$m.wav"
      echo "file '$TMP/long-$m.wav'" >> "$TMP/long.txt"
      [[ $m -lt $MIXES ]] && echo "file '$TMP/gap.wav'" >> "$TMP/long.txt"
    done
    ffmpeg -nostdin -loglevel error -y -f concat -safe 0 -i "$TMP/long.txt" -c:a pcm_s16le "$TMP/long.wav"
    tag_mp3 "$TMP/long.wav" "$target" "Long Test Mix 1" "SBR Test DJ (${name})" "$genre"
    rm -f "$TMP"/long-*.wav "$TMP/long.wav"
    continue
  fi
  mkdir -p "$OUT/$code"
  for m in $(seq 1 "$MIXES"); do
    target="$OUT/$code/${code}-test-mix-${m}.mp3"
    if [[ -s "$target" ]]; then echo "exists: $target"; continue; fi
    echo "generating $target"
    make_mix "$code" "$name" "$genre" "$bpm" "$basehz" "$m" "$TMP/mix.wav"
    tag_mp3 "$TMP/mix.wav" "$target" "Test Mix ${m}" "SBR Test DJ (${name})" "$genre"
  done
done

# Test adverts and promos (15-20 s each): a chime, then a spoken message.
mkdir -p "$OUT/ads"
ADS=(
  "promo-tournament|Street Blackjack. This weekend's tournament starts Saturday at eight. Join the table in the app.|Street Blackjack Tournament Promo"
  "promo-new-tables|Street Blackjack. New high stakes tables are open now. Test promo.|Street Blackjack New Tables Promo"
  "sponsor-a|This hour of music is brought to you by Test Sponsor A. This is a test advert.|Test Sponsor A"
  "sponsor-b|Test Sponsor B. The sound of the city. This is a test advert.|Test Sponsor B"
  "event-dj-night|Live this Friday: Street Blackjack D J night. Test event promo.|Test Event Promo"
)
for entry in "${ADS[@]}"; do
  IFS='|' read -r file text title <<<"$entry"
  target="$OUT/ads/${file}.mp3"
  if [[ -s "$target" ]]; then echo "exists: $target"; continue; fi
  echo "generating $target"
  speak "$text" "$TMP/ad.wav"
  ffmpeg -nostdin -loglevel error -y \
    -f lavfi -i "aevalsrc=0.25*sin(2*PI*880*t)*exp(-4*t)+0.2*sin(2*PI*1320*t)*exp(-4*(t-0.25))*gte(t\,0.25):s=44100:d=1.2" \
    -i "$TMP/ad.wav" \
    -filter_complex "[0:a]apad=pad_dur=0.2[c];[1:a]aresample=44100,volume=2[v];[c][v]concat=n=2:v=0:a=1,apad=pad_dur=1.5" \
    -ac 2 -c:a libmp3lame -b:a 192k -metadata title="$title" -metadata artist="Advert (test)" -metadata genre="Advert" "$target"
done

# Fallback file: played by AzuraCast if a station's playlists are ever empty or broken.
FALLBACK="$OUT/fallback.mp3"
if [[ ! -s "$FALLBACK" ]]; then
  echo "generating $FALLBACK"
  speak "Street Blackjack Radio. We'll be right back." "$TMP/fb.wav"
  ffmpeg -nostdin -loglevel error -y \
    -f lavfi -i "aevalsrc=0.08*sin(2*PI*220*t)*(0.5+0.5*sin(2*PI*t/4)):s=44100:d=30" -i "$TMP/fb.wav" \
    -filter_complex "[1:a]aresample=44100,adelay=1000|1000,volume=2[v];[0:a][v]amix=inputs=2:duration=first:normalize=0" \
    -ac 2 -c:a libmp3lame -b:a 192k -metadata title="We'll be right back" -metadata artist="Street Blackjack Radio" "$FALLBACK"
fi

cat > "$OUT/LICENSE.txt" <<'EOF'
All audio in this folder was generated by infra/scripts/generate-test-audio.sh using
ffmpeg's built-in signal generators and the espeak-ng speech synthesiser.
It contains no third-party recordings or compositions. It may be freely used,
broadcast and deleted for testing Street Blackjack Radio.
EOF

du -sh "$OUT"/* 2>/dev/null
echo "Done."
